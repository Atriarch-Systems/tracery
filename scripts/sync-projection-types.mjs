// Keep core's public data types renderer-free and identical to the visualizer contract.
import fs from 'node:fs';
const source = fs.readFileSync(new URL('../packages/visualizer/src/types.ts', import.meta.url), 'utf8').replaceAll('\r\n', '\n');
const start = source.indexOf('/** Epoch milliseconds.');
const end = source.indexOf('export interface ActivityGraphHandle');
if (start < 0 || end < start) throw new Error('Visualizer data contract boundaries changed');
const expected = '// Generated by scripts/sync-projection-types.mjs --write. Do not edit.\n' +
  '// Graph props and capture handles belong to @atriarch/tracery-visualizer.\n' + source.slice(start, end);
const target = new URL('../packages/core/src/visualizer-ext.ts', import.meta.url);
if (process.argv.includes('--write')) fs.writeFileSync(target, expected);
else if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== expected) {
  throw new Error('Core projection types drifted; run node scripts/sync-projection-types.mjs --write');
}
